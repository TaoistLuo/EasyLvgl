#!/usr/bin/env python3
"""把 .lui 里声明的图片资源转换成 LVGL 的 C 数组（相当于 Qt 的 qrc）。

.lui 顶层声明资源，路径相对于 .lui 所在目录：

    "resources": {
        "logo":    "assets/logo.png",
        "icon_ok": "assets/ok.png"
    }

控件里用 `#别名` 引用（区别于 `A:` 开头的 lv_fs 运行时路径）：

    { "type": "LImage", "props": { "src": "#logo" } }

本脚本为每个资源生成一个 `lv_image_dsc_t` 常量，并汇总一个头文件：

    <out>/logo.c   <out>/icon_ok.c      图片数据 + 描述符
    <out>/lvgl_assets.h                 全部声明（LV_IMAGE_DECLARE）

luic 生成的代码会 `#include "..."` 这个头文件，并 `set_src(&logo)`。

依赖：LVGL 官方转换器 lvgl/scripts/LVGLImage.py（需要 pypng / lz4）
      pip3 install pypng lz4
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER_PROLOGUE = """\
// Auto-generated by scripts/assets/convert_assets.py — DO NOT EDIT
#pragma once

#if defined(LV_LVGL_H_INCLUDE_SIMPLE)
#include "lvgl.h"
#elif defined(LV_BUILD_TEST)
#include "../lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

#ifdef __cplusplus
extern "C" {
#endif
"""

HEADER_EPILOGUE = """\
#ifdef __cplusplus
} /*extern "C"*/
#endif
"""


def repo_root() -> str:
    return os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def find_converter(explicit):
    if explicit:
        return os.path.abspath(explicit)
    return os.path.join(repo_root(), "lvgl", "scripts", "LVGLImage.py")


def to_png(src: str, dst_noext: str, tmpdir: str) -> str:
    """统一喂 PNG 给官方转换器；非 PNG 先用 ImageMagick 转一份。"""
    ext = os.path.splitext(src)[1].lower()
    dst = dst_noext + ".png"
    if ext == ".png":
        shutil.copyfile(src, dst)
        return dst
    if shutil.which("convert") is None:
        raise SystemExit(f"错误：{src} 不是 PNG，且未找到 ImageMagick(convert)")
    subprocess.run(["convert", src, dst], check=True)
    return dst


def convert_one(lvgl_image_py: str, src: str, alias: str, out_dir: str,
                cf: str, compress: str, tmpdir: str) -> str:
    """生成 <out_dir>/<alias>.c（符号名即 alias），返回文件路径。"""
    work = os.path.join(tmpdir, "work")
    os.makedirs(work, exist_ok=True)
    # 转换器用输入文件名推导符号名，所以拷贝成 <alias>.png
    to_png(src, os.path.join(work, alias), tmpdir)
    cmd = [sys.executable, lvgl_image_py, os.path.join(work, alias + ".png"),
           "--ofmt", "C", "--cf", cf, "--compress", compress, "-o", work]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"错误：转换 {src} 失败\n{r.stdout}\n{r.stderr}")
    produced = os.path.join(work, alias + ".c")
    if not os.path.exists(produced):
        raise SystemExit(f"错误：转换器没有产出 {produced}\n{r.stdout}")
    dst = os.path.join(out_dir, alias + ".c")
    shutil.copyfile(produced, dst)
    return dst


def main() -> int:
    ap = argparse.ArgumentParser(description="把 .lui 的图片资源配置编译成 LVGL C 数组")
    ap.add_argument("lui", help=".lui 文件（读取其中的 resources）")
    ap.add_argument("-o", "--out", default=None, help="输出目录（默认：<lui 目录>/assets）")
    ap.add_argument("--cf", default="RGB565A8",
                    help="颜色格式：RGB565A8(默认,带透明) / RGB565 / ARGB8888 / AUTO …")
    ap.add_argument("--compress", default="NONE", choices=["NONE", "RLE", "LZ4"])
    ap.add_argument("--converter", default=None, help="LVGLImage.py 路径（默认取仓库内 lvgl/scripts）")
    ap.add_argument("--include", default="assets/lvgl_assets.h",
                    help="生成代码里使用的 include 路径（默认 assets/lvgl_assets.h）")
    args = ap.parse_args()

    lui_path = os.path.abspath(args.lui)
    if not os.path.exists(lui_path):
        raise SystemExit(f"错误：找不到 {lui_path}")
    with open(lui_path, encoding="utf-8") as f:
        doc = json.load(f)

    resources = doc.get("resources") or {}
    if not resources:
        print(f"{args.lui} 没有 resources，无需转换")
        return 0

    base_dir = os.path.dirname(lui_path)
    out_dir = os.path.abspath(args.out or os.path.join(base_dir, "assets"))
    os.makedirs(out_dir, exist_ok=True)

    lvgl_image_py = find_converter(args.converter)
    if not os.path.exists(lvgl_image_py):
        raise SystemExit(f"错误：找不到图片转换器 {lvgl_image_py}")

    decls = []
    total = 0
    with tempfile.TemporaryDirectory() as tmpdir:
        for alias, rel in resources.items():
            if not IDENT_RE.match(alias):
                raise SystemExit(f"错误：资源名 '{alias}' 不是合法的 C 标识符")
            src = rel if os.path.isabs(rel) else os.path.join(base_dir, rel)
            if not os.path.exists(src):
                raise SystemExit(f"错误：资源 '{alias}' 指向的文件不存在：{src}")
            cfile = convert_one(lvgl_image_py, src, alias, out_dir,
                                args.cf, args.compress, tmpdir)
            total += os.path.getsize(cfile)
            decls.append(f"/* {alias} <- {rel} */\nLV_IMAGE_DECLARE({alias});\n")
            print(f"  {alias:20s} <- {rel}")

    header = os.path.join(out_dir, "lvgl_assets.h")
    with open(header, "w", encoding="utf-8") as f:
        f.write(HEADER_PROLOGUE)
        f.write("\n")
        f.writelines(decls)
        f.write("\n" + HEADER_EPILOGUE)

    print(f"\n完成：{len(decls)} 个资源 -> {out_dir}")
    print(f"  头文件：{header}")
    print(f"  生成代码里引用：{args.include}（luic --assets-include \"{args.include}\"）")
    print(f"  C 源码合计 {total} 字节")
    return 0


if __name__ == "__main__":
    sys.exit(main())
