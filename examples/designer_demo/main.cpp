/**
 * @file main.cpp
 * @brief Designer Demo — 使用 luic 编译产物 (dashboard_ui.hpp) 的示例
 *
 * 本示例演示完整的工作流：
 *   1. 设计器创建 ui/dashboard.lui (JSON 格式的 UI 定义)
 *   2. luic 编译器将 .lui 转换为 ui_generated/dashboard_ui.hpp
 *   3. 本文件子类化 Dashboard_UI，重写事件处理器，添加业务逻辑
 *
 * 编译: cd build && cmake .. && make -j$(nproc) designer_demo
 * 运行: bin/designer_demo
 */

#include "lvgl++/lvgl_widgets.hpp"
#include "lvgl++/core/signal_handler.hpp"
#include "dashboard_ui.hpp"
#include <unistd.h>
#include <cstdio>
#include <cstdlib>

using namespace lvgl;

static const char *getenv_default(const char *name, const char *dflt)
{
    return getenv(name) ? : dflt;
}

#if LV_USE_SDL
static void lv_linux_disp_init(void)
{
    const int width = atoi(getenv("LV_SDL_VIDEO_WIDTH") ? : "800");
    const int height = atoi(getenv("LV_SDL_VIDEO_HEIGHT") ? : "480");
    lv_sdl_window_create(width, height);
}
#else
#error Unsupported configuration
#endif

// Subclass Dashboard_UI (generated by luic) to add business logic
class Dashboard : public Dashboard_UI {
private:
    bool m_night_mode = false;

public:
    void on_slider_light_value_changed(lv_event_t* e) override {
        int val = lv_slider_get_value(m_slider_light->native());
        printf("[Light] Brightness: %d%%\n", val);
    }

    void on_btn_all_on_clicked(lv_event_t* e) override {
        printf("[Action] All devices turned ON\n");
    }

    void on_btn_all_off_clicked(lv_event_t* e) override {
        printf("[Action] All devices turned OFF\n");
    }

    void on_btn_scene_clicked(lv_event_t* e) override {
        m_night_mode = !m_night_mode;
        printf("[Scene] %s\n", m_night_mode ? "Night Mode" : "Day Mode");
    }

    void on_sw_alarm_value_changed(lv_event_t* e) override {
        bool armed = lv_obj_has_state(m_sw_alarm->native(), LV_STATE_CHECKED);
        printf("[Security] Alarm %s\n", armed ? "ARMED" : "DISARMED");
    }

    void on_cb_front_door_value_changed(lv_event_t* e) override {
        bool locked = lv_obj_has_state(m_cb_front_door->native(), LV_STATE_CHECKED);
        printf("[Door] Front door %s\n", locked ? "LOCKED" : "UNLOCKED");
    }

    void on_cb_back_door_value_changed(lv_event_t* e) override {
        bool locked = lv_obj_has_state(m_cb_back_door->native(), LV_STATE_CHECKED);
        printf("[Door] Back door %s\n", locked ? "LOCKED" : "UNLOCKED");
    }

    void on_dd_mode_value_changed(lv_event_t* e) override {
        int sel = lv_dropdown_get_selected(m_dd_mode->native());
        const char* modes[] = {"Home", "Away", "Sleep", "Vacation"};
        printf("[Mode] Selected: %s\n", modes[sel]);
    }
};

int main(void)
{
    lv_init();
    lv_linux_disp_init();
    lv_sdl_mouse_create();

    SignalHandler signal_handler;

    printf("============================================\n");
    printf("  LVGL++ Designer Demo — Smart Home Dashboard\n");
    printf("  UI generated from ui/dashboard.lui\n");
    printf("  Press Ctrl+C to exit gracefully.\n");
    printf("============================================\n\n");

    Dashboard dashboard;
    dashboard.setup();
    dashboard.bind_events();

    while (signal_handler.is_running()) {
        lv_timer_handler();
        usleep(5000);
    }

    printf("\nCleaning up resources...\n");
    return 0;
}
